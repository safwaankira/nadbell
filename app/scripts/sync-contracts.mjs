// Copies ABIs and deployed addresses from ../contracts into src/lib/chain/generated.ts.
// Run after `forge build` / a deploy:  node scripts/sync-contracts.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const contracts = path.resolve(root, "../contracts");
const names = ["MockUSDC", "StockToken", "PriceGate", "Vault", "OrderBook", "OpenCall"];

const abis = {};
for (const n of names) {
  const art = JSON.parse(fs.readFileSync(path.join(contracts, "out", `${n}.sol`, `${n}.json`), "utf8"));
  abis[n] = art.abi;
}

const deployments = {};
const dir = path.join(contracts, "deployments");
if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}

let out = "// Generated by scripts/sync-contracts.mjs. Do not edit by hand.\n\n";
for (const n of names) out += `export const ${n}Abi = ${JSON.stringify(abis[n], null, 2)} as const;\n\n`;
out += `export const deployments: Record<number, {\n  chainId: number; usdc: \`0x\${string}\`; stock: \`0x\${string}\`; gate: \`0x\${string}\`;\n  vault: \`0x\${string}\`; book: \`0x\${string}\`; openCall: \`0x\${string}\`;
  pyth: \`0x\${string}\`; feedId: \`0x\${string}\`;\n}> = ${JSON.stringify(deployments, null, 2)};\n`;
fs.writeFileSync(path.join(root, "src/lib/chain/generated.ts"), out);
// The keeper bot reads the same ABIs and addresses as plain JSON.
fs.writeFileSync(path.resolve(root, "../keeper/contracts.json"), JSON.stringify({ abis, deployments }, null, 2));
console.log("synced", names.join(", "), "deployments:", Object.keys(deployments).join(", ") || "none");
